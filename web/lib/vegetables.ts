/**
 * VegItem — one entry in the vegetable database.
 *
 * SCOPE: This dataset covers fresh, locally grown vegetables in the Netherlands only.
 * Seasonality reflects field/greenhouse harvest windows for Dutch-grown produce —
 * not import availability. "Peak" means the vegetable is at its flavour best from
 * local soil, not simply available in a supermarket.
 *
 * Do NOT add:
 *  - Imported produce that is available year-round (e.g. avocado, mango, citrus)
 *  - Fruits, berries, or nuts (separate dataset if needed)
 *  - Anything whose seasonality is driven by import rather than local harvest
 *
 * Required fields must always be filled in.
 * Optional fields (marked ?) can be left out when data isn't available yet.
 *
 * Field guide
 * -----------
 * id           Unique slug, kebab-case, English. Used as React key and future URL.
 *              Example: "butterhead-lettuce", "red-cabbage"
 *
 * name         Internal English identifier. NEVER shown to users — used only for
 *              sorting, search matching, and as a React key base. Display the `nl`
 *              field instead. Use the most common culinary term in English.
 *              Example: "Kohlrabi", "Garden peas"
 *
 * nl           Dutch name(s) as used in the Netherlands. Multiple common names separated
 *              by " / ". This is the display name shown to users in the UI.
 *              Example: "Koolrabi", "Witlof / Brussels lof"
 *
 * color        Background / fill colour for the vegetable card and illustration.
 *              Use a muted, slightly desaturated tone that evokes the vegetable's colour.
 *              Must be a hex string. Example: "#C4D88A"
 *
 * accent       Stronger version of color used for peak-bar fills, borders, and highlights.
 *              Should be noticeably darker/more saturated than color.
 *              Must be a hex string. Example: "#7B9A3D"
 *
 * family       Broad culinary/botanical category. Used for grouping and search.
 *              Use one of: "Wortel", "Blad", "Brassica", "Allium", "Peulvrucht",
 *              "Stengel", "Pompoen", "Knolgewas", "Vruchtgroente", "Paddenstoel", "Kruid"
 *              Add new categories as needed, but keep the list short.
 *
 * peak         Months when this vegetable is at its absolute best from Dutch local harvest —
 *              full flavour, peak freshness, widely available from nearby growers.
 *              Array of integers 1–12 (1 = January). Can span a year-boundary naturally:
 *              [11, 12, 1, 2] means November through February.
 *              Example: [4, 5, 6] means April, May, June.
 *              Base these on Dutch field/greenhouse cycles, not retail import windows.
 *
 * shoulder     Months when the vegetable is locally available but not at its best —
 *              just starting or winding down. Optional. Shown as "half" cells in calendar.
 *              Same integer format as peak. Still must reflect NL local harvest.
 *
 * blurb        One or two sentences of editorial copy shown on the card/detail panel.
 *              Should capture what's special, seasonal, or surprising. Avoid generic health
 *              claims. Write in the voice of an enthusiastic cook, not a nutrition label.
 *
 * storage      One or two sentences on how to store it at home after buying/harvesting.
 *              Be specific: temperature, container, days.
 *
 * prep         One or two sentences on the key preparation step before cooking — peeling,
 *              washing technique, trimming, etc. Include a signature method if one stands out.
 *
 * pairings     Array of flavour partners: other ingredients, herbs, sauces, cheeses, etc.
 *              4–8 items. Short strings — no sentences.
 *
 * substitutions  Array of what to use if this vegetable isn't available.
 *                2–4 items. Short strings.
 *
 * technique    One sentence describing the single most useful cooking technique or tip.
 *              This is the "if you only do one thing…" advice.
 *
 * nutrients?   Short string listing the main nutritional highlights (vitamins, minerals).
 *              Optional. Not shown in the current UI but useful reference for future features.
 *              Example: "Vitamin C, K, folate, potassium"
 *
 * url?         Link to the source page (e.g. velt.nu). Optional, for reference only.
 *
 * recipes?     Curated recipes that highlight this vegetable at its seasonal peak.
 *              3–5 hand-picked entries. See Recipe type for field guide.
 */
export type Recipe = {
  title: string;
  url: string;
  source: string;
  why: string;
  difficulty: "easy" | "medium" | "hard";
  time_mins: number;
};

export type VegItem = {
  id: string;
  name: string;
  nl: string;
  color: string;
  accent: string;
  family: string;
  peak: number[];
  shoulder?: number[];
  blurb: string;
  storage: string;
  prep: string;
  pairings: string[];
  substitutions: string[];
  technique: string;
  nutrients?: string;
  url?: string;
  recipes?: Recipe[];
};

export type VegStatus = "peak" | "soon" | "ending" | "shoulder" | "off";

/**
 * Returns the seasonal status of a vegetable for a given month.
 *
 * Priority order matters: a vegetable currently in shoulder (available now)
 * must not be shadowed by "soon" or "ending" — those labels imply the
 * vegetable is not yet (or no longer) accessible, which is false when a
 * shoulder month is active.
 *
 * Order: peak → shoulder → soon → ending → off
 */
export function statusFor(veg: VegItem, month: number): VegStatus {
  if (veg.peak.includes(month)) return "peak";

  // Check shoulder before soon/ending: the vegetable is available right now.
  if (veg.shoulder?.includes(month)) return "shoulder";

  // Peak is 1–2 months away but not currently available.
  const soon = veg.peak.some((m) => {
    const diff = (m - month + 12) % 12;
    return diff >= 1 && diff <= 2;
  });
  if (soon) return "soon";

  // Peak ended last month — still worth flagging as recently past.
  const prevMonth = ((month - 2 + 12) % 12) + 1;
  if (veg.peak.includes(prevMonth)) return "ending";

  return "off";
}

